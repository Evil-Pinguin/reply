// текущий сезон по реальной дате (месяцы: 0 = январь)
export function getSeason(date = new Date()) {
  const m = date.getMonth();
  return SEASONS.find((s) => s.months.includes(m)) || SEASONS[1];
}

export function seasonName(date = new Date()) {
  return getSeason(date).name;
}

